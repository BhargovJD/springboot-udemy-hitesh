public class JavaLoops {
    static void main() {
//        for loop
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

//        while loop
        int i = 10;

        while (i <= 15) {
            System.out.println(i);
            i++;
        }

//        do while loop

        int j = 100;

        do {
            System.out.println(j);
            j++;
        } while (j <= 105);

    }
}
